/**
 * Utility function to get current date in Bengali format
 */
private fun getCurrentDateBengali(): String {
    val sdf = SimpleDateFormat("dd MMMM yyyy", Locale("bn", "BD"))
    return sdf.format(Date())
}

/**
 * Utility function to get date range for report type
 */
fun getDateRangeForReportType(reportType: ReportType): ReportPeriod {
    val calendar = Calendar.getInstance()
    val endDate = calendar.time
    
    when (reportType) {
        ReportType.DAILY -> {
            calendar.add(Calendar.DAY_OF_MONTH, -1)
            val startDate = calendar.time
            return ReportPeriod(
                startDate = SimpleDateFormat("yyyy-MM-dd", Locale.getDefault()).format(startDate),
                endDate = SimpleDateFormat("yyyy-MM-dd", Locale.getDefault()).format(endDate),
                periodDescription = "গতকাল"
            )
        }
        ReportType.WEEKLY -> {
            calendar.add(Calendar.WEEK_OF_YEAR, -1)
            val startDate = calendar.time
            return ReportPeriod(
                startDate = SimpleDateFormat("yyyy-MM-dd", Locale.getDefault()).format(startDate),
                endDate = SimpleDateFormat("yyyy-MM-dd", Locale.getDefault()).format(endDate),
                periodDescription = "গত সপ্তাহ"
            )
        }
        ReportType.MONTHLY -> {
            calendar.add(Calendar.MONTH, -1)
            val startDate = calendar.time
            return ReportPeriod(
                startDate = SimpleDateFormat("yyyy-MM-dd", Locale.getDefault()).format(startDate),
                endDate = SimpleDateFormat("yyyy-MM-dd", Locale.getDefault()).format(endDate),
                periodDescription = "গত মাস"
            )
        }
        ReportType.QUARTERLY -> {
            calendar.add(Calendar.MONTH, -3)
            val startDate = calendar.time
            return ReportPeriod(
                startDate = SimpleDateFormat("yyyy-MM-dd", Locale.getDefault()).format(startDate),
                endDate = SimpleDateFormat("yyyy-MM-dd", Locale.getDefault()).format(endDate),
                periodDescription = "গত ত্রৈমাসিক"
            )
        }
        ReportType.YEARLY -> {
            calendar.add(Calendar.YEAR, -1)
            val startDate = calendar.time
            return ReportPeriod(
                startDate = SimpleDateFormat("yyyy-MM-dd", Locale.getDefault()).format(startDate),
                endDate = SimpleDateFormat("yyyy-MM-dd", Locale.getDefault()).format(endDate),
                periodDescription = "গত বছর"
            )
        }
        ReportType.CUSTOM -> {
            return ReportPeriod(
                startDate = SimpleDateFormat("yyyy-MM-dd", Locale.getDefault()).format(endDate),
                endDate = SimpleDateFormat("yyyy-MM-dd", Locale.getDefault()).format(endDate),
                periodDescription = "কাস্টম"
            )
        }
    }
}

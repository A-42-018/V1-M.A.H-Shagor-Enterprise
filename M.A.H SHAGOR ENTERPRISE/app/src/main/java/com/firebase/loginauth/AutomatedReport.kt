package com.firebase.loginauth

import java.text.SimpleDateFormat
import java.util.*

/**
 * Data class representing an automated business report
 */
data class AutomatedReport(
    val id: String = UUID.randomUUID().toString(),
    val reportType: ReportType = ReportType.DAILY,
    val reportDate: String = getCurrentDateBengali(),
    val generatedAt: Long = System.currentTimeMillis(),
    val reportPeriod: ReportPeriod = ReportPeriod(),
    val salesSummary: SalesSummary = SalesSummary(),
    val orderSummary: OrderSummary = OrderSummary(),
    val customerSummary: CustomerSummary = CustomerSummary(),
    val inventorySummary: InventorySummary = InventorySummary(),
    val expenseSummary: ExpenseSummary = ExpenseSummary(),
    val financialSummary: FinancialSummary = FinancialSummary(),
    val topPerformers: TopPerformers = TopPerformers(),
    val insights: List<BusinessInsight> = emptyList(),
    val recommendations: List<String> = emptyList(),
    val isAutoGenerated: Boolean = true,
    val status: ReportStatus = ReportStatus.GENERATED
)

/**
 * Enum for report types
 */
enum class ReportType(val displayNameBn: String, val displayNameEn: String) {
    DAILY("দৈনিক", "Daily"),
    WEEKLY("সাপ্তাহিক", "Weekly"),
    MONTHLY("মাসিক", "Monthly"),
    QUARTERLY("ত্রৈমাসিক", "Quarterly"),
    YEARLY("বার্ষিক", "Yearly"),
    CUSTOM("কাস্টম", "Custom")
}

/**
 * Enum for report status
